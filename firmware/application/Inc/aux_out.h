/* Дополнительные каналы выхода — семь линий (CM-HW-02):
 *   №1 = PA14 (SWCLK — конфликт с SWD, включается только битом владения),
 *   №2 = PA15 (бывший OUT4), №3 = PC10 (бывший OUT1), №4 = PC11 (OUT2),
 *   №5 = PC12 (OUT3), №6 = PD2 (конфликт CAN2_TERM), №7 = PB3 (CAN1_TERM).
 * Порядок новый; легаси-нумерация CMD_AUX_SET 1..4 = PC10/PC11/PC12/PA15
 * переводится в 3/4/5/2 на уровне протокола — старые приложения ездят
 * по тем же физическим пинам, молчаливой переадресации нет.
 *
 * Пины 1/6/7 совместно используемы: владение задаётся маской
 * aux_pins_mask в CFGH (DeviceConfig_GetAuxPinsMask) — бит пина =
 * «пин отдан каналу», иначе канал недоступен (CMD отвечает 0x02), а
 * пин остаётся под SWD/TERM. Совместного управления одним пином
 * нет — TERM-запись игнорируется на отданных пинах (can_bridge.c).
 *
 * Управление — CMD_AUX_SET_EXT (proto >= 13): режимы Вкл/Выкл/
 * импульсы/ШИМ + срок работы для Вкл и ШИМ. Команда ставит программу;
 * дальше фронты крутит AuxOut_Poll() из главного цикла — ПК не нужен.
 *
 * Логическое состояние канала отделено от мгновенного уровня GPIO:
 * AuxOut_IsActive() = «канал работает» (ON/PWM/PULSE, включая низкую
 * фазу ШИМ и ШИМ с 0% заполнения), AuxOut_Get() = уровень на ноге.
 * Переходы логического состояния ставятся в очередь событий —
 * их разбирает ГЛ (trigger.c), лимит очереди с диагностикой переполнения.
 *
 * ШИМ программный (HAL_GetTick, шаг 1 мс): практический потолок
 * ~500 Гц при 50% заполнении, для больших частот нужен аппаратный
 * TIM — отражено ограничением в PROTOCOL.md и в UI. */

#ifndef AUX_OUT_H
#define AUX_OUT_H

#include <stdint.h>

#define AUX_CH_COUNT   7U
#define AUX_MODE_OFF   0U
#define AUX_MODE_ON    1U
#define AUX_MODE_PULSE 2U
#define AUX_MODE_PWM   3U

/* Пины с разделяемым назначением: биты в aux_pins_mask (CFGH).
 * Каналы 2..5 доступны всегда; биты для них в маске игнорируются. */
#define AUX_OWN_PA14   (1U << 0U)  /* канал 1 — освобождение SWCLK */
#define AUX_OWN_PD2    (1U << 5U)  /* канал 6 — вместо CAN2_TERM */
#define AUX_OWN_PB3    (1U << 6U)  /* канал 7 — вместо CAN1_TERM */
#define AUX_OWN_ALWAYS 0x1EU       /* каналы 2..5 — без конфликтов */

/* Глубина очередь событий переходов каналов (вкл/выкл). При
 * переполнении события теряются со счётчиком AuxOut_EventsDropped —
 * кольцевая программа ГЛ не может заблокировать автомат каналов. */
#define AUX_EVENT_DEPTH 8U

void    AuxOut_Init(uint8_t own_mask);
/* Доступность канала с учётом маски владения пинами. */
uint8_t AuxOut_IsAvailable(uint8_t channel);
/* Текущая маска владения (для ответов протоколу). */
uint8_t AuxOut_OwnedMask(void);
/* Перевладение пинами: обновляет маску из CFGH и перенастраивает
 * GPIO. Пины, уходящие из-под AUX, остаются входами/вернутся TERM —
 * вызывается из CMD_AUX_MAP после записи CFGH. */
void    AuxOut_ApplyOwnedMask(uint8_t own_mask);

/* Одна команда на канал: mode + параметры импульсов/ШИМ + общий срок
 * работы time_ms (Вкл/ШИМ; 0 — до «Выкл»). Аргументы проверяются ДО
 * смены состояния: невалидная команда возвращает 0, не портя режим.
 * Коды: 0 — неверные параметры/канал недоступен, 1 — принято. */
uint8_t AuxOut_Set(uint8_t channel, uint8_t mode,
                   uint16_t pulse_on_ms, uint16_t pulse_off_ms,
                   uint16_t pulse_count, uint16_t pwm_freq_hz,
                   uint8_t pwm_duty_pct, uint32_t pwm_time_ms);
void    AuxOut_Poll(void);
/* Текущий логический уровень канала (0/1) — для диагностики. */
uint8_t AuxOut_Get(uint8_t channel);
/* Логическая активность: режим ON/PULSE/PWM (в т.ч. низкая фаза ШИМ
 * и ШИМ 0% заполнения). Именно она — условие «канал работает». */
uint8_t AuxOut_IsActive(uint8_t channel);
/* Текущий режим канала (AUX_MODE_*) — для CMD_AUX_GET. */
uint8_t AuxOut_GetMode(uint8_t channel);

/* Очередь событий переходов каналов для ГЛ: извлекает самое старое
 * событие (канал 1..7, is_on = новое логическое состояние). Возвращает
 * 1 при наличии события, 0 — очередь пуста. */
uint8_t AuxOut_TakeEvent(uint8_t *channel_out, uint8_t *is_on_out);
/* Счётчик потерянных событий (переполнение очереди) — диагностика
 * кольцевых программ ГЛ. */
uint32_t AuxOut_EventsDropped(void);

#endif /* AUX_OUT_H */
